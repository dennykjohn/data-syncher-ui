import React, { useEffect, useMemo, useState } from "react";

import {
  Box,
  Button,
  Checkbox,
  CloseButton,
  Dialog,
  Flex,
  IconButton,
  Input,
  InputGroup,
  Portal,
  Table,
  Text,
  VStack,
} from "@chakra-ui/react";

import { IoMdOptions } from "react-icons/io";
import {
  MdDragIndicator,
  MdKeyboardArrowDown,
  MdKeyboardArrowUp,
  MdKeyboardDoubleArrowDown,
  MdKeyboardDoubleArrowUp,
  MdLock,
  MdSearch,
} from "react-icons/md";
import { PiKeyFill } from "react-icons/pi";
import { TbArrowsExchange, TbSparkles } from "react-icons/tb";

import { toaster } from "@/components/ui/toaster";
import { Tooltip } from "@/components/ui/tooltip";
import {
  type ExcelConditionalFormat,
  type TableFieldInfo,
  type TargetFieldMeta,
} from "@/types/connectors";

import { isPrimaryKey } from "../../utils/validation";
import {
  computeSelectedTargetFields,
  getRenameInfoForSource,
  isColumnRequiredByScript,
  isColumnUsedInConditionalFormatting,
  isGeneratedColumn,
  mapSelectedOutputToSourceFields,
} from "./helpers/targetFieldUtils";

interface FieldSelectionModalProps {
  open: boolean;
  onClose: () => void;
  tableName: string;
  tableFields: Record<string, string | TableFieldInfo>;
  initialSelectedFields: string[] | null | undefined;
  targetFields?: Record<string, TargetFieldMeta> | null;
  excelConditionalFormats?: ExcelConditionalFormat[] | null;
  scriptText?: string | null;
  onSave: (_fields: string[]) => void;
  isSaving: boolean;
}

interface AvailableFieldItem {
  name: string;
  sourceName?: string;
  targetName: string;
  dataType: string;
  isGenerated: boolean;
  isRenamed: boolean;
  renameLabel?: string;
  isPK: boolean;
  isLocked: boolean;
  lockedReason?: string;
}

const FieldSelectionModal = ({
  open,
  onClose,
  tableName,
  tableFields,
  initialSelectedFields,
  targetFields,
  excelConditionalFormats,
  scriptText,
  onSave,
  isSaving,
}: FieldSelectionModalProps) => {
  const [selectedFields, setSelectedFields] = useState<string[]>([]);
  const [searchQuery, setSearchQuery] = useState("");
  const [activeSelectedFields, setActiveSelectedFields] = useState<string[]>(
    [],
  );
  const [draggedField, setDraggedField] = useState<string | null>(null);

  // Compute available items combining source table fields and script-generated columns
  const availableItems = useMemo<AvailableFieldItem[]>(() => {
    const items: AvailableFieldItem[] = [];

    // 1. Source fields from tableFields
    for (const [col, fieldInfo] of Object.entries(tableFields)) {
      const dataType =
        typeof fieldInfo === "string"
          ? fieldInfo
          : fieldInfo?.data_type || "object";
      const isPK = isPrimaryKey(col, fieldInfo);
      const renameInfo = getRenameInfoForSource(col, targetFields);
      const isUsedInCF = isColumnUsedInConditionalFormatting(
        col,
        excelConditionalFormats,
        targetFields,
      );
      const isRequiredInScript = isColumnRequiredByScript(
        col,
        targetFields,
        scriptText,
      );

      const isLocked = isUsedInCF || isRequiredInScript;
      let lockedReason: string | undefined;
      if (isUsedInCF && isRequiredInScript) {
        lockedReason =
          "Required by Python transform script and referenced in Excel conditional formatting rules";
      } else if (isUsedInCF) {
        lockedReason = "Referenced in Excel conditional formatting rules";
      } else if (isRequiredInScript) {
        lockedReason = "Required by Python transform script";
      }

      items.push({
        name: col,
        sourceName: col,
        targetName: renameInfo.targetName,
        dataType,
        isGenerated: false,
        isRenamed: renameInfo.isRenamed,
        renameLabel: renameInfo.isRenamed ? renameInfo.label : undefined,
        isPK,
        isLocked,
        lockedReason,
      });
    }

    // 2. Newly generated columns produced by Python transform
    if (targetFields) {
      for (const [colName, meta] of Object.entries(targetFields)) {
        if (isGeneratedColumn(meta)) {
          items.push({
            name: colName,
            targetName: colName,
            dataType: meta.data_type || "object",
            isGenerated: true,
            isRenamed: false,
            isPK: Boolean(meta.is_primary_key),
            isLocked: true,
            lockedReason: "Generated by Python transform script",
          });
        }
      }
    }

    return items;
  }, [tableFields, targetFields, excelConditionalFormats, scriptText]);

  const generatedFieldSet = useMemo(() => {
    const set = new Set<string>();
    if (targetFields) {
      for (const [colName, meta] of Object.entries(targetFields)) {
        if (isGeneratedColumn(meta)) {
          set.add(colName);
        }
      }
    }
    return set;
  }, [targetFields]);

  useEffect(() => {
    if (open) {
      const initial = computeSelectedTargetFields(
        initialSelectedFields,
        targetFields,
        tableFields,
      );
      const normal = initial.filter((f) => !generatedFieldSet.has(f));
      const generated = initial.filter((f) => generatedFieldSet.has(f));
      // Short delay to avoid cascading render lint issues while resetting state
      const timer = setTimeout(() => {
        setSelectedFields([...normal, ...generated]);
        setActiveSelectedFields([]);
        setSearchQuery("");
      }, 0);
      return () => clearTimeout(timer);
    }
  }, [
    open,
    initialSelectedFields,
    targetFields,
    tableFields,
    generatedFieldSet,
  ]);

  const filteredItems = useMemo(() => {
    const q = searchQuery.trim().toLowerCase();
    return availableItems
      .filter((item) => {
        if (!q) return true;
        return (
          item.name.toLowerCase().includes(q) ||
          item.targetName.toLowerCase().includes(q) ||
          (item.sourceName && item.sourceName.toLowerCase().includes(q))
        );
      })
      .sort((a, b) => {
        // Primary keys first, then regular fields, then generated fields
        if (a.isPK && !b.isPK) return -1;
        if (!a.isPK && b.isPK) return 1;
        if (!a.isGenerated && b.isGenerated) return -1;
        if (a.isGenerated && !b.isGenerated) return 1;
        return 0;
      });
  }, [availableItems, searchQuery]);

  const toggleField = (item: AvailableFieldItem) => {
    const isCurrentlySelected =
      selectedFields.includes(item.targetName) ||
      selectedFields.includes(item.name);

    if (isCurrentlySelected) {
      // User is attempting to DESELECT
      if (item.isLocked) {
        toaster.warning({
          title: item.isGenerated ? "Generated Column" : "Column in Use",
          description: `"${item.name}" cannot be deselected: ${item.lockedReason}`,
        });
        return;
      }

      // Deselect allowed
      setSelectedFields((prev) =>
        prev.filter((f) => f !== item.targetName && f !== item.name),
      );
      setActiveSelectedFields((active) =>
        active.filter((f) => f !== item.targetName && f !== item.name),
      );
    } else {
      // User is SELECTING
      setSelectedFields((prev) => {
        const firstGenIdx = prev.findIndex((f) => generatedFieldSet.has(f));
        if (firstGenIdx === -1) {
          return [...prev, item.targetName];
        }
        const copy = [...prev];
        copy.splice(firstGenIdx, 0, item.targetName);
        return copy;
      });
    }
  };

  const handleDragStart = (field: string) => {
    if (generatedFieldSet.has(field)) return;
    setDraggedField(field);
  };

  const handleDragOver = (e: React.DragEvent) => {
    e.preventDefault();
  };

  const handleDrop = (targetField: string) => {
    if (!draggedField || draggedField === targetField) return;
    if (generatedFieldSet.has(draggedField)) return;

    setSelectedFields((prev) => {
      const newList = [...prev];
      const draggedIndex = newList.indexOf(draggedField);
      if (draggedIndex === -1) return prev;

      newList.splice(draggedIndex, 1);

      const firstGenIdx = newList.findIndex((f) => generatedFieldSet.has(f));
      const maxNormalIdx = firstGenIdx === -1 ? newList.length : firstGenIdx;

      let targetIndex = newList.indexOf(targetField);
      if (targetIndex === -1 || targetIndex > maxNormalIdx) {
        targetIndex = maxNormalIdx;
      }

      newList.splice(targetIndex, 0, draggedField);
      return newList;
    });
    setDraggedField(null);
  };

  const handleSelectAll = () => {
    const allTargetNames = availableItems.map((item) => item.targetName);
    const uniqueTargets = Array.from(new Set(allTargetNames));
    const normal = uniqueTargets.filter((f) => !generatedFieldSet.has(f));
    const generated = uniqueTargets.filter((f) => generatedFieldSet.has(f));
    setSelectedFields([...normal, ...generated]);
  };

  const handleRowClick = (
    field: string,
    index: number,
    event: React.MouseEvent,
  ) => {
    if (event.ctrlKey || event.metaKey) {
      setActiveSelectedFields((prev) =>
        prev.includes(field)
          ? prev.filter((f) => f !== field)
          : [...prev, field],
      );
    } else if (event.shiftKey && activeSelectedFields.length > 0) {
      const lastSelectedField =
        activeSelectedFields[activeSelectedFields.length - 1];
      const startIndex = selectedFields.indexOf(lastSelectedField);
      const endIndex = index;

      const start = Math.min(startIndex, endIndex);
      const end = Math.max(startIndex, endIndex);
      const newSelections = selectedFields.slice(start, end + 1);

      setActiveSelectedFields(
        Array.from(new Set([...activeSelectedFields, ...newSelections])),
      );
    } else {
      setActiveSelectedFields([field]);
    }
  };

  const selectedIndices = activeSelectedFields
    .map((f) => selectedFields.indexOf(f))
    .filter((i) => i !== -1)
    .sort((a, b) => a - b);

  const firstGenIndex = selectedFields.findIndex((f) =>
    generatedFieldSet.has(f),
  );
  const maxNormalIndex =
    firstGenIndex === -1 ? selectedFields.length - 1 : firstGenIndex - 1;
  const hasSelectedGenerated = activeSelectedFields.some((f) =>
    generatedFieldSet.has(f),
  );
  const isAtTop = selectedIndices.length === 0 || selectedIndices.includes(0);
  const isAtBottom =
    selectedIndices.length === 0 ||
    selectedIndices.some((idx) => idx >= maxNormalIndex);

  const moveField = (direction: "top" | "up" | "down" | "bottom") => {
    if (activeSelectedFields.length === 0 || hasSelectedGenerated) return;

    const newFields = [...selectedFields];
    const currentIndices = activeSelectedFields
      .map((f) => newFields.indexOf(f))
      .filter((i) => i !== -1)
      .sort((a, b) => a - b);

    if (currentIndices.length === 0) return;

    const firstGenIdx = newFields.findIndex((f) => generatedFieldSet.has(f));
    const maxNormalIdx =
      firstGenIdx === -1 ? newFields.length - 1 : firstGenIdx - 1;

    if (direction === "up") {
      if (currentIndices[0] === 0) return;
      for (const index of currentIndices) {
        [newFields[index], newFields[index - 1]] = [
          newFields[index - 1],
          newFields[index],
        ];
      }
    } else if (direction === "down") {
      if (currentIndices[currentIndices.length - 1] >= maxNormalIdx) return;
      for (let i = currentIndices.length - 1; i >= 0; i--) {
        const index = currentIndices[i];
        [newFields[index], newFields[index + 1]] = [
          newFields[index + 1],
          newFields[index],
        ];
      }
    } else if (direction === "top") {
      if (currentIndices[0] === 0) return;
      const normalItems =
        firstGenIdx === -1 ? newFields : newFields.slice(0, firstGenIdx);
      const genItems = firstGenIdx === -1 ? [] : newFields.slice(firstGenIdx);
      const itemsToMove = currentIndices.map((i) => newFields[i]);
      const remainingNormal = normalItems.filter(
        (f) => !activeSelectedFields.includes(f),
      );
      newFields.length = 0;
      newFields.push(...itemsToMove, ...remainingNormal, ...genItems);
    } else if (direction === "bottom") {
      if (
        currentIndices[currentIndices.length - 1] >= maxNormalIdx &&
        currentIndices.length === maxNormalIdx - currentIndices[0] + 1
      ) {
        return;
      }
      const normalItems =
        firstGenIdx === -1 ? newFields : newFields.slice(0, firstGenIdx);
      const genItems = firstGenIdx === -1 ? [] : newFields.slice(firstGenIdx);
      const itemsToMove = currentIndices.map((i) => newFields[i]);
      const remainingNormal = normalItems.filter(
        (f) => !activeSelectedFields.includes(f),
      );
      newFields.length = 0;
      newFields.push(...remainingNormal, ...itemsToMove, ...genItems);
    }

    setSelectedFields(newFields);
  };

  const handleSave = () => {
    // Preserve source table column names when saving to Snowflake configuration
    const sourceFields = mapSelectedOutputToSourceFields(
      selectedFields,
      targetFields,
    );
    onSave(sourceFields);
  };

  return (
    <Dialog.Root lazyMount open={open} size="xl">
      <Portal>
        <Dialog.Backdrop bg="blackAlpha.600" backdropFilter="blur(4px)" />
        <Dialog.Positioner>
          <Dialog.Content
            borderRadius="xl"
            boxShadow="2xl"
            bg="white"
            overflow="hidden"
          >
            <Dialog.Header
              bg="brand.50"
              borderBottomWidth="1px"
              borderColor="brand.100"
            >
              <Dialog.Title color="brand.800" fontWeight="bold">
                Select and Order Fields: {tableName}
              </Dialog.Title>
            </Dialog.Header>
            <Dialog.Body p={6}>
              <VStack align="stretch" gap={6}>
                <InputGroup
                  width="100%"
                  endElement={<MdSearch size={22} color="gray" />}
                >
                  <Input
                    placeholder="Search fields by name..."
                    value={searchQuery}
                    onChange={(e) => setSearchQuery(e.target.value)}
                    variant="outline"
                    colorPalette="brand"
                    borderRadius="full"
                    bg="gray.50"
                  />
                </InputGroup>

                <Flex gap={6} height="450px">
                  {/* Left: Available Fields */}
                  <Box
                    flex={1}
                    borderWidth={1}
                    borderRadius="lg"
                    borderColor="gray.200"
                    bg="gray.50"
                    overflow="hidden"
                    display="flex"
                    flexDirection="column"
                  >
                    <Box
                      p={3}
                      bg="white"
                      borderBottomWidth={1}
                      borderColor="gray.100"
                    >
                      <Flex justifyContent="space-between" alignItems="center">
                        <Text
                          fontWeight="bold"
                          fontSize="xs"
                          color="gray.600"
                          letterSpacing="wider"
                        >
                          Available Fields ({filteredItems.length})
                        </Text>
                        <Button
                          size="xs"
                          variant="ghost"
                          onClick={handleSelectAll}
                          colorPalette="brand"
                        >
                          Select all
                        </Button>
                      </Flex>
                    </Box>
                    <Box flex={1} overflowY="auto">
                      <Table.Root
                        size="sm"
                        variant="line"
                        style={{ borderCollapse: "separate", borderSpacing: 0 }}
                      >
                        <Table.Header position="sticky" top={0} zIndex={2}>
                          <Table.Row bg="gray.50">
                            <Table.ColumnHeader
                              position="sticky"
                              top={0}
                              zIndex={2}
                              width="40px"
                              py={2}
                              pl={3}
                              bg="gray.50"
                              borderBottomWidth={1}
                              borderColor="gray.200"
                            ></Table.ColumnHeader>
                            <Table.ColumnHeader
                              position="sticky"
                              top={0}
                              zIndex={2}
                              py={2}
                              bg="gray.50"
                              borderBottomWidth={1}
                              borderColor="gray.200"
                            >
                              Field
                            </Table.ColumnHeader>
                            <Table.ColumnHeader
                              position="sticky"
                              top={0}
                              zIndex={2}
                              py={2}
                              pr={3}
                              bg="gray.50"
                              borderBottomWidth={1}
                              borderColor="gray.200"
                            >
                              Type
                            </Table.ColumnHeader>
                          </Table.Row>
                        </Table.Header>
                        <Table.Body>
                          {filteredItems.map((item) => {
                            const isSelected =
                              selectedFields.includes(item.targetName) ||
                              selectedFields.includes(item.name);

                            return (
                              <Table.Row
                                key={item.name}
                                _hover={{ bg: "brand.50" }}
                                transition="background 0.2s"
                                bg={isSelected ? "brand.50" : "transparent"}
                              >
                                <Table.Cell py={2} pl={3}>
                                  <Tooltip
                                    content={item.lockedReason}
                                    disabled={!item.isLocked}
                                  >
                                    <Box
                                      cursor={
                                        item.isLocked
                                          ? "not-allowed"
                                          : "pointer"
                                      }
                                      onClick={() => toggleField(item)}
                                      display="inline-block"
                                    >
                                      <Checkbox.Root
                                        colorPalette="brand"
                                        checked={isSelected}
                                        pointerEvents="none"
                                      >
                                        <Checkbox.HiddenInput />
                                        <Checkbox.Control />
                                      </Checkbox.Root>
                                    </Box>
                                  </Tooltip>
                                </Table.Cell>
                                <Table.Cell
                                  py={2}
                                  fontSize="xs"
                                  fontWeight={
                                    isSelected ? "semibold" : "normal"
                                  }
                                >
                                  <Flex
                                    alignItems="center"
                                    gap={1.5}
                                    flexWrap="wrap"
                                  >
                                    {item.isPK && (
                                      <Box
                                        color="yellow.500"
                                        title="Primary Key"
                                      >
                                        <PiKeyFill />
                                      </Box>
                                    )}
                                    <Text>{item.targetName}</Text>

                                    {item.isRenamed && (
                                      <Tooltip
                                        content={`Renamed from "${item.sourceName}"`}
                                      >
                                        <Box
                                          as="span"
                                          display="inline-flex"
                                          alignItems="center"
                                          color="blue.500"
                                          fontSize="15px"
                                          cursor="default"
                                        >
                                          <TbArrowsExchange />
                                        </Box>
                                      </Tooltip>
                                    )}

                                    {item.isGenerated && (
                                      <Tooltip content="Generated by Python transform script">
                                        <Box
                                          as="span"
                                          display="inline-flex"
                                          alignItems="center"
                                          color="purple.500"
                                          fontSize="15px"
                                          cursor="default"
                                        >
                                          <TbSparkles />
                                        </Box>
                                      </Tooltip>
                                    )}

                                    {item.isLocked && !item.isGenerated && (
                                      <Tooltip content={item.lockedReason}>
                                        <Box color="gray.400" fontSize="11px">
                                          <MdLock />
                                        </Box>
                                      </Tooltip>
                                    )}
                                  </Flex>
                                </Table.Cell>
                                <Table.Cell
                                  py={2}
                                  pr={3}
                                  fontSize="xs"
                                  color="gray.500"
                                >
                                  {item.dataType}
                                </Table.Cell>
                              </Table.Row>
                            );
                          })}
                        </Table.Body>
                      </Table.Root>
                    </Box>
                  </Box>

                  {/* Right: Selected & Order (Output Columns) */}
                  <Box
                    flex={1}
                    borderWidth={1}
                    borderRadius="lg"
                    borderColor="brand.100"
                    bg="white"
                    overflow="hidden"
                    display="flex"
                    flexDirection="column"
                    boxShadow="sm"
                  >
                    <Box
                      p={3}
                      bg="brand.50"
                      borderBottomWidth={1}
                      borderColor="brand.100"
                    >
                      <Flex
                        justifyContent="space-between"
                        alignItems="center"
                        gap={2}
                      >
                        <Text
                          fontWeight="bold"
                          fontSize="xs"
                          color="brand.800"
                          letterSpacing="wider"
                          whiteSpace="nowrap"
                        >
                          Output Fields ({selectedFields.length})
                        </Text>

                        <Flex gap={1} alignItems="center">
                          <IconButton
                            aria-label="Move To Top"
                            size="xs"
                            variant="subtle"
                            disabled={isAtTop || hasSelectedGenerated}
                            onClick={() => moveField("top")}
                          >
                            <MdKeyboardDoubleArrowUp />
                          </IconButton>
                          <IconButton
                            aria-label="Move Up"
                            size="xs"
                            variant="subtle"
                            disabled={isAtTop || hasSelectedGenerated}
                            onClick={() => moveField("up")}
                          >
                            <MdKeyboardArrowUp />
                          </IconButton>
                          <IconButton
                            aria-label="Move Down"
                            size="xs"
                            variant="subtle"
                            disabled={isAtBottom || hasSelectedGenerated}
                            onClick={() => moveField("down")}
                          >
                            <MdKeyboardArrowDown />
                          </IconButton>
                          <IconButton
                            aria-label="Move To Bottom"
                            size="xs"
                            variant="subtle"
                            disabled={isAtBottom || hasSelectedGenerated}
                            onClick={() => moveField("bottom")}
                          >
                            <MdKeyboardDoubleArrowDown />
                          </IconButton>
                        </Flex>
                      </Flex>
                    </Box>
                    <Box flex={1} overflowY="auto" p={3}>
                      {selectedFields.length === 0 ? (
                        <Flex
                          height="100%"
                          direction="column"
                          alignItems="center"
                          justifyContent="center"
                          gap={2}
                        >
                          <IoMdOptions size={40} color="#CBD5E0" />
                          <Text
                            color="gray.400"
                            fontSize="xs"
                            textAlign="center"
                            px={4}
                          >
                            No fields selected.
                            <br />
                            All fields will be included in the export.
                          </Text>
                        </Flex>
                      ) : (
                        <VStack align="stretch" gap={2}>
                          {selectedFields.map((field, index) => {
                            const isActive =
                              activeSelectedFields.includes(field);
                            const meta = targetFields?.[field];
                            const isGenerated = isGeneratedColumn(meta);
                            const isRenamed = Boolean(
                              meta?.source_name && meta.source_name !== field,
                            );
                            const sourceName = meta?.source_name;

                            return (
                              <Flex
                                key={field}
                                p={2.5}
                                bg={isActive ? "brand.50" : "white"}
                                borderWidth={1}
                                borderColor={
                                  isActive ? "brand.200" : "gray.100"
                                }
                                borderRadius="md"
                                alignItems="center"
                                gap={3}
                                transition="all 0.2s"
                                cursor="pointer"
                                onClick={(e) => handleRowClick(field, index, e)}
                                draggable={!isGenerated}
                                onDragStart={() => handleDragStart(field)}
                                onDragOver={handleDragOver}
                                onDrop={() => handleDrop(field)}
                                onDragEnd={() => setDraggedField(null)}
                              >
                                {isGenerated ? (
                                  <Tooltip content="Generated columns stay at the end and cannot be reordered">
                                    <Box color="gray.300" cursor="not-allowed">
                                      <MdDragIndicator />
                                    </Box>
                                  </Tooltip>
                                ) : (
                                  <Box color="#A0AEC0" cursor="grab">
                                    <MdDragIndicator />
                                  </Box>
                                )}
                                <Flex
                                  flex={1}
                                  alignItems="center"
                                  gap={1.5}
                                  minW="0"
                                >
                                  <Text
                                    fontSize="xs"
                                    fontWeight="medium"
                                    color={isActive ? "brand.800" : "gray.700"}
                                    truncate
                                  >
                                    {field}
                                  </Text>
                                  {isRenamed && (
                                    <Tooltip
                                      content={`Renamed from "${sourceName}"`}
                                    >
                                      <Box
                                        as="span"
                                        display="inline-flex"
                                        alignItems="center"
                                        color="blue.500"
                                        fontSize="15px"
                                        flexShrink={0}
                                        cursor="default"
                                      >
                                        <TbArrowsExchange />
                                      </Box>
                                    </Tooltip>
                                  )}
                                  {isGenerated && (
                                    <Tooltip content="Generated by Python transform script">
                                      <Box
                                        as="span"
                                        display="inline-flex"
                                        alignItems="center"
                                        color="purple.500"
                                        fontSize="15px"
                                        flexShrink={0}
                                        cursor="default"
                                      >
                                        <TbSparkles />
                                      </Box>
                                    </Tooltip>
                                  )}
                                </Flex>
                              </Flex>
                            );
                          })}
                        </VStack>
                      )}
                    </Box>
                    <Box
                      p={2}
                      borderTopWidth={1}
                      borderColor="gray.100"
                      bg="gray.50"
                    >
                      <Text fontSize="10px" color="gray.500" textAlign="center">
                        Click to select · Ctrl+click or Shift+click for
                        multi-select · Drag to reorder
                      </Text>
                    </Box>
                  </Box>
                </Flex>

                <Text fontSize="sm" color="gray.600" fontWeight="medium">
                  {selectedFields.length} output fields configured for export
                </Text>
              </VStack>
            </Dialog.Body>
            <Dialog.Footer
              bg="gray.50"
              borderTopWidth="1px"
              borderColor="gray.100"
              p={4}
            >
              <Button variant="ghost" onClick={onClose} mr={3}>
                Cancel
              </Button>
              <Button
                colorPalette="brand"
                loading={isSaving}
                onClick={handleSave}
                px={8}
                borderRadius="full"
              >
                Save Field Selection
              </Button>
            </Dialog.Footer>
            <Dialog.CloseTrigger asChild>
              <CloseButton
                size="sm"
                onClick={onClose}
                position="absolute"
                right={4}
                top={4}
              />
            </Dialog.CloseTrigger>
          </Dialog.Content>
        </Dialog.Positioner>
      </Portal>
    </Dialog.Root>
  );
};

export default FieldSelectionModal;
