import {
  type ExcelConditionalFormat,
  type TargetFieldMeta,
} from "@/types/connectors";

export interface RenameInfo {
  isRenamed: boolean;
  sourceName: string;
  targetName: string;
  label: string;
}

/**
 * Returns rename metadata if the target field was renamed from a source column.
 */
export const getRenameInfo = (
  targetColName: string,
  meta?: TargetFieldMeta | null,
): RenameInfo => {
  if (meta?.source_name && meta.source_name !== targetColName) {
    return {
      isRenamed: true,
      sourceName: meta.source_name,
      targetName: targetColName,
      label: targetColName,
    };
  }
  return {
    isRenamed: false,
    sourceName: meta?.source_name ?? targetColName,
    targetName: targetColName,
    label: targetColName,
  };
};

/**
 * Returns rename metadata given a source column name, finding if it was renamed to a different target column.
 */
export const getRenameInfoForSource = (
  sourceColName: string,
  targetFields?: Record<string, TargetFieldMeta> | null,
): RenameInfo => {
  if (targetFields) {
    for (const [targetName, meta] of Object.entries(targetFields)) {
      if (
        meta.source_name &&
        meta.source_name.toLowerCase() === sourceColName.toLowerCase()
      ) {
        const isRenamed = meta.source_name !== targetName;
        return {
          isRenamed,
          sourceName: meta.source_name,
          targetName,
          label: targetName,
        };
      }
    }
  }
  return {
    isRenamed: false,
    sourceName: sourceColName,
    targetName: sourceColName,
    label: sourceColName,
  };
};

/**
 * Checks whether a target field is newly generated by the Python transformation.
 */
export const isGeneratedColumn = (meta?: TargetFieldMeta | null): boolean => {
  if (!meta) return false;
  return Boolean(meta.generated || meta.source_name === null);
};

/**
 * Computes the effective list of output columns (target columns) for display,
 * reflecting renames (e.g. A6 → B6) and generated columns (generated: true).
 */
export const computeSelectedTargetFields = (
  selectedSourceFields: string[] | null | undefined,
  targetFields: Record<string, TargetFieldMeta> | undefined | null,
  tableFields?: Record<string, unknown> | null,
): string[] => {
  const hasTargetFields = targetFields && Object.keys(targetFields).length > 0;
  if (!hasTargetFields) {
    if (selectedSourceFields && selectedSourceFields.length > 0) {
      return [...selectedSourceFields];
    }
    return tableFields ? Object.keys(tableFields) : [];
  }

  // Map source column names to their target names (for renames and untouched fields)
  const sourceToTarget: Record<string, string> = {};
  for (const [targetName, meta] of Object.entries(targetFields)) {
    if (meta.source_name) {
      sourceToTarget[meta.source_name] = targetName;
    } else if (!meta.generated) {
      sourceToTarget[targetName] = targetName;
    }
  }

  const effectiveSelectedSources =
    selectedSourceFields && selectedSourceFields.length > 0
      ? selectedSourceFields
      : tableFields
        ? Object.keys(tableFields)
        : Object.keys(targetFields);

  const result: string[] = [];
  const addedSet = new Set<string>();

  // 1. Preserve original selection order, mapping source column names to target names
  for (const src of effectiveSelectedSources) {
    const targetName = sourceToTarget[src] || (targetFields[src] ? src : null);
    if (targetName && targetFields[targetName] && !addedSet.has(targetName)) {
      result.push(targetName);
      addedSet.add(targetName);
    }
  }

  // 2. Renamed columns produced by the script are also included in output
  for (const [targetName, meta] of Object.entries(targetFields)) {
    if (
      meta.source_name &&
      meta.source_name !== targetName &&
      !addedSet.has(targetName)
    ) {
      result.push(targetName);
      addedSet.add(targetName);
    }
  }

  // 3. Newly generated columns produced by the script are always placed at the end of output
  for (const [targetName, meta] of Object.entries(targetFields)) {
    if (isGeneratedColumn(meta) && !addedSet.has(targetName)) {
      result.push(targetName);
      addedSet.add(targetName);
    }
  }

  return result;
};

/**
 * Converts a list of selected output/target column names back to original source field names
 * in user order, filtering out generated columns (which don't exist in source database).
 */
export const mapSelectedOutputToSourceFields = (
  selectedOutputFields: string[],
  targetFields?: Record<string, TargetFieldMeta> | null,
): string[] => {
  if (!targetFields || Object.keys(targetFields).length === 0) {
    return [...selectedOutputFields];
  }

  const result: string[] = [];
  const added = new Set<string>();

  for (const col of selectedOutputFields) {
    const meta = targetFields[col];
    // If it's a generated column, it has no source name and cannot be queried in Snowflake
    if (meta && isGeneratedColumn(meta)) {
      continue;
    }
    const sourceName = meta?.source_name || col;
    if (!added.has(sourceName)) {
      result.push(sourceName);
      added.add(sourceName);
    }
  }

  return result;
};

/**
 * Determines whether a column is referenced by Excel conditional formatting rules.
 * Handles both source column name and renamed target column name.
 */
export const isColumnUsedInConditionalFormatting = (
  colName: string,
  rules: ExcelConditionalFormat[] | undefined | null,
  targetFields?: Record<string, TargetFieldMeta> | null,
): boolean => {
  if (!rules || rules.length === 0) return false;

  const colLower = colName.trim().toLowerCase();

  // Find corresponding source/target names
  const candidateNames = new Set<string>([colLower]);
  if (targetFields) {
    for (const [targetName, meta] of Object.entries(targetFields)) {
      if (targetName.toLowerCase() === colLower && meta.source_name) {
        candidateNames.add(meta.source_name.toLowerCase());
      }
      if (meta.source_name?.toLowerCase() === colLower) {
        candidateNames.add(targetName.toLowerCase());
      }
    }
  }

  return rules.some((rule) => {
    if (
      rule.column_name &&
      candidateNames.has(rule.column_name.toLowerCase())
    ) {
      return true;
    }
    if (
      rule.condition_column_name &&
      candidateNames.has(rule.condition_column_name.toLowerCase())
    ) {
      return true;
    }
    if (Array.isArray(rule.target_columns)) {
      if (
        rule.target_columns.some((tc) =>
          candidateNames.has(String(tc).toLowerCase()),
        )
      ) {
        return true;
      }
    }
    if (Array.isArray(rule.conditions)) {
      if (
        rule.conditions.some(
          (c) => c.column && candidateNames.has(String(c.column).toLowerCase()),
        )
      ) {
        return true;
      }
    }
    return false;
  });
};

/**
 * Checks if a source column is referenced in the Python transform script
 * (e.g. df['A6'], df["A6"], df.A6, or columns={'A6': ...}).
 */
export const isColumnUsedInScript = (
  colName: string,
  scriptText?: string | null,
): boolean => {
  if (!scriptText || !scriptText.trim()) return false;
  const escaped = colName.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

  // 1. Quoted references: df['COL'], df["COL"], {'COL': ...}, columns=['COL']
  const quotedRegex = new RegExp(`['"]${escaped}['"]`, "i");
  if (quotedRegex.test(scriptText)) return true;

  // 2. Attribute access: df.COL, source_df.COL, __source_df.COL
  const dotRegex = new RegExp(
    `\\b(?:df|source_df|__source_df)\\s*\\.\\s*${escaped}\\b`,
    "i",
  );
  if (dotRegex.test(scriptText)) return true;

  return false;
};

/**
 * Checks if a source column is required by the Python transform configuration:
 * - If it was explicitly renamed (source_name !== targetName), the original source
 *   column is required so the Python transformation can generate the renamed target column.
 * - If the column name is directly referenced in the Python script text (e.g. df['COL']).
 *
 * Untouched pass-through columns that merely exist in source_df and target_df
 * without being referenced in the script are NOT locked, allowing the user
 * to freely select or deselect them in Field Selection.
 */
export const isColumnRequiredByScript = (
  sourceColName: string,
  targetFields?: Record<string, TargetFieldMeta> | null,
  scriptText?: string | null,
): boolean => {
  // 1. Check if the column was explicitly RENAMED (source_name !== targetName)
  if (targetFields && Object.keys(targetFields).length > 0) {
    const colLower = sourceColName.trim().toLowerCase();
    for (const [targetName, meta] of Object.entries(targetFields)) {
      if (
        meta.source_name &&
        meta.source_name.toLowerCase() === colLower &&
        meta.source_name.toLowerCase() !== targetName.toLowerCase()
      ) {
        return true;
      }
    }
  }

  // 2. Check if the column is directly referenced in the Python script
  if (scriptText && isColumnUsedInScript(sourceColName, scriptText)) {
    return true;
  }

  return false;
};
